function main() {
  let content = fs.readFileSync(DATA_PATH, "utf8");
  const lines = content.split("\n");

  const out = lines.map((line) => {
    if (!line.includes('category: "Tiger Data"')) return line;
    for (const [term, category] of Object.entries(CATEGORY_MAP)) {
      if (line.includes(`term: "${term}"`)) {
        return line.replace('category: "Tiger Data"', `category: "${category}"`);
      }
    }
    return line;
  });

  content = out.join("\n");
  const newCategories =
    'export const categories = ["TimescaleDB", "Storage", "Time-series", "Cloud", "Security", "Operations", "Observability", "AI & vectors", "PostgreSQL", "Data & migration"];';
  content = content.replace(
    /export const categories = \[.*?\];/s,
    newCategories
  );

  fs.writeFileSync(DATA_PATH, content, "utf8");
  console.log("Updated glossary-data.ts with new categories.");
}

main();
